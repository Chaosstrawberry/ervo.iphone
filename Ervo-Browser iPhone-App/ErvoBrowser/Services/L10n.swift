enum L {
    static let isGerman: Bool = {
        let lang = Locale.preferredLanguages.first ?? "en"
        return lang.lowercased().hasPrefix("de")
    }()

    static func t(_ key: String) -> String {
        (isGerman ? de[key] : en[key]) ?? en[key] ?? key
    }

    /// Formats: replaces {0}, {1}, … with the given arguments.
    static func f(_ key: String, _ args: String...) -> String {
        var text = t(key)
        for (index, value) in args.enumerated() {
            text = text.replacingOccurrences(of: "{\(index)}", with: value)
        }
        return text
    }

